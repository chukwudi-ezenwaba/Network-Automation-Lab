#!/bin/bash

#############################################################################
# Ubuntu LTS System Information Collector
# Purpose: Gather and display comprehensive system information for Ubuntu
# Usage: ./ubuntu_system_info.sh
#############################################################################

echo "=================================================================================="
echo "              UBUNTU SERVER SYSTEM INFORMATION REPORT"
echo "=================================================================================="
echo ""

# Display timestamp
echo "Report Generated: $(date '+%Y-%m-%d %H:%M:%S')"
echo ""

echo "=================================================================================="
echo "1. OPERATING SYSTEM INFORMATION"
echo "=================================================================================="
echo ""
cat /etc/os-release
echo ""

echo "=================================================================================="
echo "2. HOSTNAME CONFIGURATION"
echo "=================================================================================="
echo ""
echo "Current Hostname: $(hostname)"
echo ""
echo "Hosts File Contents:"
cat /etc/hosts
echo ""

echo "=================================================================================="
echo "3. NETWORK INTERFACES"
echo "=================================================================================="
echo ""
ip a
echo ""

echo "=================================================================================="
echo "4. DNS RESOLUTION CONFIGURATION"
echo "=================================================================================="
echo ""
systemd-resolve --status
echo ""

echo "=================================================================================="
echo "5. SYSTEM DATE AND TIME"
echo "=================================================================================="
echo ""
timedatectl
echo ""

echo "=================================================================================="
echo "6. SYSTEM UPTIME"
echo "=================================================================================="
echo ""
uptime
echo ""

echo "=================================================================================="
echo "7. CPU INFORMATION"
echo "=================================================================================="
echo ""
lscpu
echo ""

echo "=================================================================================="
echo "8. MEMORY INFORMATION"
echo "=================================================================================="
echo ""
free -h
echo ""

echo "=================================================================================="
echo "9. DISK USAGE"
echo "=================================================================================="
echo ""
df -h
echo ""

echo "=================================================================================="
echo "10. KERNEL VERSION"
echo "=================================================================================="
echo ""
uname -r
echo ""

echo "=================================================================================="
echo "Report Complete"
echo "=================================================================================="
